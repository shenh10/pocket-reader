package cc.shenhan.pocketreader;

import android.os.SystemClock;
import androidx.test.core.app.ActivityScenario;
import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.platform.app.InstrumentationRegistry;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.json.JSONObject;
import android.os.ParcelFileDescriptor;
import java.io.FileInputStream;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicReference;
import static org.junit.Assert.*;

@RunWith(AndroidJUnit4.class)
public class NativeDailyAssetsTest {
    private String evaluate(ActivityScenario<MainActivity> app, String expression) throws Exception {
        CountDownLatch done = new CountDownLatch(1);
        AtomicReference<String> result = new AtomicReference<>();
        app.onActivity(activity -> activity.getBridge().getWebView().evaluateJavascript(
            "(()=>{try{return (" + expression + ");}catch(e){return String(e);}})()",
            value -> { result.set(value); done.countDown(); }
        ));
        assertTrue("WebView JavaScript callback timed out", done.await(10, TimeUnit.SECONDS));
        return result.get();
    }
    private void until(ActivityScenario<MainActivity> app, String expression) throws Exception {
        long deadline = SystemClock.elapsedRealtime() + 30000;
        String result;
        do {
            result = evaluate(app, expression);
            if ("true".equals(result)) return;
            SystemClock.sleep(250);
        } while (SystemClock.elapsedRealtime() < deadline);
        screenshot("native-daily-failure.png");
        android.util.Log.e("PocketReaderTest", evaluate(app,"JSON.stringify({url:location.href,state:document.readyState,title:document.title,classes:document.documentElement.className,styles:[...document.styleSheets].map(s=>({href:s.href,rules:s.cssRules.length})),html:document.head.innerHTML})"));
        fail("WebView check failed: " + expression + " result=" + result + " url=" + evaluate(app,"location.href"));
    }
    private void styledDaily(ActivityScenario<MainActivity> app, String search) throws Exception {
        until(app, "location.pathname === '/ai-infra-board/index.html' && location.search === " + JSONObject.quote(search) + " && document.readyState === 'complete' && document.title === 'AI Infra Merge Board' && !!document.querySelector('.topBand') && !!window.Capacitor && document.documentElement.classList.contains('pr-native')");
        assertEquals("true",evaluate(app,"Capacitor.isNativePlatform() && document.documentElement.classList.contains('pr-native')"));
        until(app,"!window.__leavingDocument && [...document.styleSheets].some(s => s.href?.includes('/ai-infra-board/assets/') && s.cssRules.length > 0) && getComputedStyle(document.querySelector('.topBand')).display === 'grid'");
        assertEquals("\"grid\"",evaluate(app,"getComputedStyle(document.querySelector('.topBand')).display"));
        assertEquals("\"flex\"",evaluate(app,"getComputedStyle(document.querySelector('.brandBlock')).display"));
        assertEquals("true",evaluate(app,"document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1"));
    }
    private void screenshot(String name) throws Exception {
        // Download survives Gradle uninstalling the app after the instrumented test.
        try (ParcelFileDescriptor pipe = InstrumentationRegistry.getInstrumentation().getUiAutomation()
                .executeShellCommand("screencap -p /sdcard/Download/" + name);
             FileInputStream input = new FileInputStream(pipe.getFileDescriptor())) {
            input.readAllBytes();
        }
    }
    @Test public void dailyTabAndLegacyDirectoryLoadActualStyles() throws Exception {
        try (ActivityScenario<MainActivity> app = ActivityScenario.launch(MainActivity.class)) {
            until(app,"!!document.querySelector('.pr-nav a[href*=\"ai-infra-board\"]')");
            evaluate(app,"document.querySelector('.pr-nav a[href*=\"ai-infra-board\"]').click()");
            styledDaily(app, "");
            // The hosted API can load independently of CSS. Capture actual cards if available.
            long deadline=SystemClock.elapsedRealtime()+20000;
            while(!"true".equals(evaluate(app,"!!document.querySelector('.prCard')")) && SystemClock.elapsedRealtime()<deadline) SystemClock.sleep(250);
            screenshot("native-daily-styled.png");
            // Deep links generated by already-installed releases still use this directory form.
            evaluate(app,"(window.__leavingDocument=true, location.assign('/ai-infra-board/?date=2026-11-20'))");
            styledDaily(app, "?date=2026-11-20");
            assertEquals("\"?date=2026-11-20\"",evaluate(app,"location.search"));
            evaluate(app,"location.assign('/nvidia-docs/kernels/')");
            until(app,"location.pathname === '/nvidia-docs/kernels/index.html' && document.readyState === 'complete' && !!document.querySelector('.wrap')");
            until(app,"[...document.styleSheets].some(s => s.href?.endsWith('/atlas.css') && s.cssRules.length > 0)");
        }
    }
}
